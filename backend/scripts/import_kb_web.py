def _upsert(db, sublib: str, key: str, platform: str, title: str, content: str, tags: list, meta: dict, sort_order: int):
    row = db.query(KnowledgeItem).filter(
        KnowledgeItem.sublib == sublib, KnowledgeItem.key == key).first()
    if row is None:
        db.add(KnowledgeItem(sublib=sublib, key=key, platform=platform, title=title,
                             content=content, tags=tags, meta=meta, sort_order=sort_order))
        return "add"
    row.platform = platform
    row.title = title
    row.content = content
    row.tags = tags
    row.meta = meta
    row.sort_order = sort_order
    return "upd"


