import re
from .models import KnowledgeItem


def _extract(content: str, label: str) -> str:
    """从爆款拆解正文中抽取形如【人设钩子】xxx 的一行。"""
    if not content:
        return ""
    m = re.search(r"【" + label + r"】([^\n]*)", content)
    return m.group(1).strip() if m else ""


def retrieve_kb(session, platform: str, genre: str) -> dict[str, Any]:
    """从数据库知识库实时检索：平台规则、类型套路、相关爆款拆解。
    生成器据此把真实爆款套路与来源注入剧本，既更智能又可对外宣讲。"""
    items = session.query(KnowledgeItem).all()
    plat = next((i for i in items if i.sublib == "platform" and i.key == platform), None)
    if plat is None:
        # 回退到种子内置平台规则（DB 未同步时仍能生成）
        seed_p = PLATFORM_ALL.get(platform)
        if seed_p:
            plat = type("X", (), {"title": seed_p["name"], "meta": {"source": seed_p.get("source", "")},
                                   "content": ""})()
    gen = next((i for i in items if i.sublib == "genre" and i.key == genre), None)
    cases = [i for i in items if i.sublib == "asset"
             and ("案例" in (i.title or "") or (i.key or "").startswith("asset_case"))]

    def relevant(i: KnowledgeItem) -> bool:
        tags = i.tags or []
        title = i.title or ""
        return (genre in tags) or (platform in tags) or (genre in title) or (platform in title)

    related = [i for i in cases if relevant(i)][:3]
    # 无匹配爆款时，回退到通用爆款方法论案例，保证每部剧都带来源参考
    if not related:
        method = next((i for i in items if i.key == "asset_method_chaijie"), None)
        if method:
            related = [method]

    refs = []
    if plat:
        refs.append({"title": plat.title, "source": (plat.meta or {}).get("source", "")})
    if gen:
        refs.append({"title": gen.title, "source": (gen.meta or {}).get("source", "")})

    case_refs = []
    for c in related:
        case_refs.append({
            "title": c.title,
            "source": (c.meta or {}).get("source", ""),
            "ren_she": _extract(c.content, "人设钩子") or _extract(c.content, "核心设定"),
            "kai_pian": _extract(c.content, "开篇钩子") or _extract(c.content, "核心设定"),
            "why": _extract(c.content, "为什么爆"),
        })

    return {
        "platform_item": plat,
        "genre_item": gen,
        "related_cases": related,
        "refs": refs,
        "case_refs": case_refs,
    }
