def seed_items() -> list[dict]:
    """返回知识库种子条目（含来源），供首次启动/重新采集写入数据库。

    每个条目带 platform 字段用于二级导航分组：
    - hongguo / douyin / kuaishou：特定平台
    - general：跨平台通用
    """
    items = []
    # 平台规则：仅展示核心字段，来源单独存入 meta
    platform_display = ["aspect", "ep_duration", "hook_3s", "pass_rules", "redlines",
                        "title_rule", "cover_rule", "fenzhang", "subject", "aigc"]
    for k, v in PLATFORM_ALL.items():
        src = v.get("source", "")
        content = "\n".join(f"{kk}：{v[kk]}" for kk in platform_display if kk in v)
        content += f"\n\n【来源】{src}"
        items.append({"sublib": "platform", "platform": k, "key": k, "title": v["name"],
                      "content": content, "tags": ["平台规则", k],
                      "meta": {"source": src, "collected_at": COLLECTED_AT},
                      "sort_order": 0})
    # 类型套路（跨平台）
    for i, (k, v) in enumerate(GENRES.items()):
        src = "抖音/红果/快手 2026 平台政策 + 短剧类型结构方法论"
        content = "\n".join(f"{kk}：{v[kk]}" for kk in
                          ["archetypes", "opening_hook", "structure", "emotion_curve",
                           "ending", "beat", "example_titles", "trend"] if kk in v)
        content += f"\n\n【来源】{src}"
        items.append({"sublib": "genre", "platform": "general", "key": k, "title": f"{k}类型套路",
                      "content": content, "tags": ["类型套路", k],
                      "meta": {"source": src, "collected_at": COLLECTED_AT},
                      "sort_order": i})
    # 风格样本（跨平台）
    for i, s in enumerate(STYLE_SAMPLES):
        items.append({"sublib": "style", "platform": "general", "sort_order": i, **s})
    # 剧本资产：按案例归属平台归类
    for i, a in enumerate(ASSET_SAMPLES):
        plat = _infer_platform(a)
        a2 = {**a, "sublib": "asset", "platform": plat, "sort_order": i}
        # 让 tags 也带上平台标签，便于二级导航检索
        tags = list(a2.get("tags", []))
        if plat in ("hongguo", "douyin", "kuaishou") and plat not in tags:
            tags.append(plat)
        a2["tags"] = tags
        items.append(a2)
    # AI短剧知识库（向导）：用户引导/答疑条目，sublib=guide, platform=guide（专属节点）
    for i, g in enumerate(GUIDE):
        g2 = {**g, "sublib": "guide", "platform": "guide", "sort_order": i}
        items.append(g2)
    return items


def _infer_platform(item: dict) -> str:
    """根据条目内容/标签推断其归属平台（用于二级导航）。"""
    text = ((item.get("title") or "") + " " + (item.get("content") or "") + " " +
            " ".join(item.get("tags") or []))
    # 红果典型关键词
    if any(k in text for k in ["红果", "douyu", "doubao"]):
        return "douyin"
    if any(k in text for k in ["红果", "hongguo", "千部计划"]):
        return "hongguo"
    if any(k in text for k in ["快手", "kuaishou", "磁力新剧", "星芒", "可灵"]):
        return "kuaishou"
    if "红果" in text and "短剧" in text:
        return "hongguo"
    return "general"


